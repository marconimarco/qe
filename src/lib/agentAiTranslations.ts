const AGENT_UI_MAP: Record<AgentLang, AgentUiStrings> = {
  it: IT_UI,
  en: EN_UI,
  zh: ZH_UI,
  de: DE_UI,
  fr: FR_UI,
  ja: JA_UI,
};

export function resolveAgentLang(language: LanguageCode): AgentLang {
  if (language in AGENT_UI_MAP) return language as AgentLang;
  return 'en';
}

export function getAgentUi(language: LanguageCode): AgentUiStrings {
  return AGENT_UI_MAP[resolveAgentLang(language)];
}

export function getLocalizedSectorName(canonicalSector: string, language: LanguageCode): string {
  const lang = resolveAgentLang(language);
  return SECTOR_DISPLAY_NAMES[canonicalSector]?.[lang] || SECTOR_DISPLAY_NAMES[canonicalSector]?.en || canonicalSector;
}

export function getLocalizedTaxonomicTexts(taxKey: string, language: LanguageCode): TaxonomicLocalizedText {
  const lang = resolveAgentLang(language);
  const entry = TAXONOMIC_LOCALIZED[taxKey] || TAXONOMIC_LOCALIZED.finanza;
  return entry[lang] || entry.en;
}
